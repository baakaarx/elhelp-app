test('تنبيه المخزون لا يعرض حالة مطمئنة قديمة لو الاتصال علق',async({page})=>{
 await page.goto('/');await submitLogin(page,E2E_ADMIN.email,E2E_ADMIN.password);await expect(page.getByRole('button',{name:'خروج'})).toBeVisible();
 let release!:()=>void;const hold=new Promise<void>(r=>release=r);
 await page.route('**/api/warehouse/low-stock',async route=>{await hold;await route.abort().catch(()=>{});});
 await page.getByRole('button',{name:'المخازن',exact:true}).click();
 const alerts=page.getByLabel('تنبيهات نقص المخزون');await expect(alerts).toContainText('جارٍ تحميل التنبيهات');
 await expect(alerts.getByRole('alert')).toContainText('تعذر تحديث التنبيهات',{timeout:11000});
 await expect(alerts).not.toContainText('لا يوجد رصيد مسجّل أقل');
 release();await page.unroute('**/api/warehouse/low-stock');
 await page.evaluate(()=>document.dispatchEvent(new Event('visibilitychange')));
 await expect(alerts.getByRole('alert')).toHaveCount(0,{timeout:5000});
});

